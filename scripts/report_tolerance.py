#!/usr/bin/env python3
"""Report tolerance ranges per proposition.

    python scripts/report_tolerance.py FILE.yaml [FILE.yaml ...] --out project/reports/tolerance.md

Pass derived statement sets. For each tolerance proposition it lists every
statement's range, optimum, class value and curve, by claimant and response,
and flags:

  - non-overlapping ranges, when the units match: sources disagree about
    where the organism lives (often because they judged different responses,
    or different regions);
  - unit mismatches: ranges in different units are listed side by side and
    never converted silently;
  - class values on no scale (a practitioner's "wet"), which are said as such
    rather than given a scale they do not have.

It does not aggregate ranges into one envelope: whether to take the union, the
intersection or an evidence-weighted envelope is an open question (proposal
Q3). Findings, not errors: the script always exits 0.
"""

import argparse
import sys
from itertools import combinations
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import derive_propositions as dp  # noqa: E402


def claimant(s):
    return next((c.get("contributor") for c in s.get("contributions") or [] if c.get("role") == "author"), "?")


def overlaps(a, b):
    """Closed-interval overlap; a missing end is open."""
    lo_a = a.get("min", float("-inf"))
    hi_a = a.get("max", float("inf"))
    lo_b = b.get("min", float("-inf"))
    hi_b = b.get("max", float("inf"))
    return lo_a <= hi_b and lo_b <= hi_a


def fmt_range(r):
    if not r:
        return ""
    lo, hi = r.get("min"), r.get("max")
    span = f"{lo:g} to {hi:g}" if lo is not None and hi is not None else (
        f"at least {lo:g}" if lo is not None else f"at most {hi:g}")
    return f"{span} {r.get('unit', '')}".strip()


def analyse(sets, schema=dp.DEFAULT_SCHEMA):
    g = {x["group"]: x for x in dp.load_groups(schema, all_groups=True)}["tolerance"]
    statements, props, names = {}, [], {}
    for data in sets:
        for n in data.get("nodes") or []:
            names.setdefault(n["id"], n.get("name", n["id"]))
        for s in data.get(g["statements_slot"]) or []:
            statements[s["id"]] = s
        props += data.get(g["propositions_slot"]) or []
    out = []
    for p in sorted(props, key=lambda p: p["id"]):
        rows, flags = [], []
        for sid in p.get("derived_from_statements") or []:
            s = statements.get(sid) or {}
            q = s.get("predicate_qualifiers") or {}
            cv = q.get("class_value") or {}
            rows.append({"statement": sid, "claimant": claimant(s), "response": q.get("response", ""),
                         "range": q.get("range"), "optimum": q.get("optimum"), "class_value": cv,
                         "curve": q.get("response_curve") or []})
            if cv and not cv.get("scale"):
                flags.append(f"`{sid}`: class value \"{cv.get('value')}\" is on no scale (the source's own words)")
        ranged = [r for r in rows if r["range"]]
        for a, b in combinations(ranged, 2):
            ua, ub = a["range"].get("unit"), b["range"].get("unit")
            if ua != ub:
                flags.append(f"unit mismatch: `{a['statement']}` ({ua}) and `{b['statement']}` ({ub}); "
                             "not converted")
            elif not overlaps(a["range"], b["range"]):
                flags.append(f"non-overlapping ranges: `{a['statement']}` ({fmt_range(a['range'])}, "
                             f"{a['response'] or 'response not given'}) and `{b['statement']}` "
                             f"({fmt_range(b['range'])}, {b['response'] or 'response not given'})")
        out.append({"proposition": p, "rows": rows, "flags": flags})
    return out, names


def render(results, names):
    n = lambda x: names.get(x, x)  # noqa: E731
    lines = ["# Tolerance report", "",
             "Generated by `scripts/report_tolerance.py`. Ranges are listed by claimant and "
             "response and never aggregated into one envelope (proposal Q3), and never converted "
             "between units.", "",
             f"- Tolerance propositions: {len(results)}",
             f"- With flags: {sum(bool(r['flags']) for r in results)}", ""]
    for r in results:
        p = r["proposition"]
        place = ", ".join(p.get("place") or []) or "no place"
        lines += [f"## {n(p['subject'])} {p['predicate'].replace('_', ' ')} {n(p['object'])}", "",
                  f"`{p['id']}` · scope {p.get('scope')} · {place}", "",
                  "| Statement | Claimant | Response | Range | Optimum | Class value | Curve points |",
                  "|---|---|---|---|---|---|---|"]
        for row in r["rows"]:
            cv = row["class_value"]
            cv_text = (cv.get("value", "") + (f" ({cv['scale']})" if cv.get("scale") else " (no scale)")) if cv else ""
            opt = row["optimum"]
            opt_text = f"{opt.get('value'):g} {opt.get('unit', '')}".strip() if opt else ""
            lines.append(f"| `{row['statement']}` | {row['claimant']} | {row['response']} | "
                         f"{fmt_range(row['range'])} | {opt_text} | {cv_text} | {len(row['curve']) or ''} |")
        lines.append("")
        for f in r["flags"]:
            lines.append(f"- {f}")
        if r["flags"]:
            lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("files", type=Path, nargs="+")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    sets = [yaml.safe_load(f.read_text(encoding="utf-8")) or {} for f in args.files]
    results, names = analyse(sets)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(results, names) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {len(results)} tolerance proposition(s), "
          f"{sum(bool(r['flags']) for r in results)} flagged")


if __name__ == "__main__":
    main()
